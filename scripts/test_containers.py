#!/usr/bin/env python3
"""install-deps.sh against real package managers in real containers.

Local only. Run with docker or podman installed and network access:

    CHECKS_CONTAINER_TESTS=1 python3 -I scripts/test_containers.py

The tests pull the node, python, golang, and rust images. Each fixture holds a
canary: a file the install would run if the project could make it run code (a
pnpmfile, a .yarnrc yarn-path, a setup.py behind -e, a cargo rustc override, a
rust-toolchain.toml toolchain). A canary that runs writes PWNED everywhere the
container can write, and every test checks that no PWNED exists afterwards.
"""
from __future__ import annotations

import json
import os
import shutil
import subprocess
import tempfile
import unittest
from pathlib import Path

SCRIPTS = Path(__file__).resolve().parent
RUNTIME = os.environ.get("CHECKS_DOCKER") or shutil.which("docker") or shutil.which("podman")
ENABLED = os.environ.get("CHECKS_CONTAINER_TESTS") == "1" and RUNTIME is not None

CANARY_SH = """#!/bin/sh
for d in /cache /work/.checks-deps /work/node_modules "$PWD" "$PWD/node_modules"; do
  echo pwned > "$d/PWNED" 2>/dev/null
done
exit 1
"""
CANARY_JS = """const fs = require("fs");
for (const d of ["/cache", "/work/.checks-deps", "/work/node_modules", process.cwd(), process.cwd() + "/node_modules"]) {
  try { fs.writeFileSync(d + "/PWNED", "pwned"); } catch {}
}
"""
CANARY_PY = """import os
for d in ("/cache", "/work/.checks-deps", os.getcwd()):
    try:
        open(os.path.join(d, "PWNED"), "w").write("pwned")
    except OSError:
        pass
from setuptools import setup
setup(name="canary", version="0.0.0")
"""

MS_PNPM_LOCK = """lockfileVersion: '9.0'

settings:
  autoInstallPeers: true
  excludeLinksFromLockfile: false

importers:

  .:
    dependencies:
      ms:
        specifier: 2.1.3
        version: 2.1.3

packages:

  ms@2.1.3:
    resolution: {integrity: sha512-6FlzubTLZG3J2a/NVCAleEhjzq5oxgHyaCU9yYXvcLsvoVaHJq/s5xXI6/XXP6tz7R9xAOtHnSO/tXtF3WRTlA==}

snapshots:

  ms@2.1.3: {}
"""
MS_YARN_LOCK = """# THIS IS AN AUTOGENERATED FILE. DO NOT EDIT THIS FILE DIRECTLY.
# yarn lockfile v1


ms@2.1.3:
  version "2.1.3"
  resolved "https://registry.yarnpkg.com/ms/-/ms-2.1.3.tgz#574c8138ce1d2b5861f0b44579dbadd60c6615b2"
  integrity sha512-6FlzubTLZG3J2a/NVCAleEhjzq5oxgHyaCU9yYXvcLsvoVaHJq/s5xXI6/XXP6tz7R9xAOtHnSO/tXtF3WRTlA==
"""
LINKED_NPM_LOCK = {
    "name": "a",
    "version": "1.0.0",
    "lockfileVersion": 3,
    "requires": True,
    "packages": {
        "": {"name": "a", "version": "1.0.0", "dependencies": {"b": "file:../b"}},
        "../b": {"version": "1.0.0"},
        "node_modules/b": {"resolved": "../b", "link": True},
    },
}
CARGO_TOML = """[package]
name = "fx"
version = "0.1.0"
edition = "2021"

[dependencies]
cfg-if = "=1.0.0"
"""
CARGO_LOCK = """# This file is automatically @generated by Cargo.
# It is not intended for manual editing.
version = 4

[[package]]
name = "cfg-if"
version = "1.0.0"
source = "registry+https://github.com/rust-lang/crates.io-index"
checksum = "baf1de4339761588bc0619e3cbc0120ee582ebb74b53b4efbf79117bd2da40fd"

[[package]]
name = "fx"
version = "0.1.0"
dependencies = [
 "cfg-if",
]
"""
FILE_DEP_PNPM_LOCK = """lockfileVersion: '9.0'

settings:
  autoInstallPeers: true
  excludeLinksFromLockfile: false

importers:

  .:
    dependencies:
      b:
        specifier: file:../b
        version: file:../b

packages:

  b@file:../b:
    resolution: {directory: ../b, type: directory}

snapshots:

  b@file:../b: {}
"""
FILE_DEP_YARN_LOCK = """# THIS IS AN AUTOGENERATED FILE. DO NOT EDIT THIS FILE DIRECTLY.
# yarn lockfile v1


"b@file:../b":
  version "1.0.0"
"""
GO_MOD = """module example.com/fx

go 1.23

require github.com/google/uuid v1.6.0
"""
GO_SUM = """github.com/google/uuid v1.6.0 h1:NIvaJDMOsjHA8n1jAhLSgzrAzy1Hgr+hNrb57e+94F0=
github.com/google/uuid v1.6.0/go.mod h1:TIyPZe4MgqvfeYDBFedMoGGpEw/LqOeaOT+nhxU+yHo=
"""


@unittest.skipUnless(ENABLED, "set CHECKS_CONTAINER_TESTS=1 with docker or podman installed")
class ContainerInstallTest(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        root = Path(self.tmp.name)
        self.work = root / "work"
        self.work.mkdir()
        self.cache = root / "cache"
        self.bin = root / "bin"
        self.bin.mkdir()
        if not shutil.which("timeout"):
            # GNU timeout isn't on macOS: drop the options and the duration.
            shim = self.bin / "timeout"
            shim.write_text('#!/usr/bin/env bash\nwhile [[ "$1" == -* ]]; do shift; done\nshift\nexec "$@"\n')
            shim.chmod(0o755)
        offline = self.bin / "docker-offline"
        offline.write_text(
            "#!/usr/bin/env bash\n"
            f'if [ "$1" = run ]; then shift; exec "{RUNTIME}" run --network none "$@"; fi\n'
            f'exec "{RUNTIME}" "$@"\n'
        )
        offline.chmod(0o755)
        self.results = Path("/tmp/checks-deps.txt")
        self.changed = Path("/tmp/changed-files.txt")

    def tearDown(self):
        self.tmp.cleanup()
        self.results.unlink(missing_ok=True)
        self.changed.unlink(missing_ok=True)

    def write(self, rel: str, text: str, executable: bool = False) -> Path:
        path = self.work / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text)
        if executable:
            path.chmod(0o755)
        return path

    def commit(self) -> None:
        git = ["git", "-C", str(self.work), "-c", "user.email=t@example.com", "-c", "user.name=t"]
        subprocess.run(git + ["init", "-q"], check=True)
        subprocess.run(git + ["add", "-A"], check=True)
        subprocess.run(git + ["commit", "-qm", "fixture"], check=True)

    def install(self, *changed: str, offline: bool = False) -> list[list[str]]:
        self.changed.write_text("".join(f"{path}\n" for path in changed))
        env = {
            "PATH": f"{self.bin}:{os.environ['PATH']}",
            "HOME": os.environ.get("HOME", "/tmp"),
            "GITHUB_WORKSPACE": str(self.work),
            "CHECKS_INSTALL": "auto",
            "CHECKS_DEPS_CACHE": str(self.cache),
            "CHECKS_DOCKER": str(self.bin / "docker-offline") if offline else RUNTIME,
        }
        result = subprocess.run(
            ["bash", str(SCRIPTS / "install-deps.sh")], env=env, capture_output=True, text=True, timeout=900,
        )
        self.assertEqual(result.returncode, 0, result.stdout + result.stderr)
        self.output = result.stdout + result.stderr
        return [line.split("\t") for line in self.results.read_text().splitlines()]

    def assert_no_canary(self) -> None:
        found = [str(p) for base in (self.work, self.cache) if base.exists() for p in base.rglob("PWNED")]
        self.assertEqual(found, [], self.output)

    def test_pnpm_ignores_the_pnpmfile_and_packagemanager(self):
        self.write("package.json", json.dumps({"name": "p", "packageManager": "pnpm@10.0.0", "dependencies": {"ms": "2.1.3"}}))
        self.write("pnpm-lock.yaml", MS_PNPM_LOCK)
        self.write(".pnpmfile.cjs", CANARY_JS + "module.exports = { hooks: { readPackage(p) { " + CANARY_JS.replace("\n", " ") + " return p; } } };\n")
        self.write("index.ts", "export {};\n")
        self.commit()
        rows = self.install("index.ts")
        self.assertEqual(rows, [["pnpm", "node_modules", "ok", ""]], self.output)
        self.assertTrue((self.work / "node_modules" / "ms" / "package.json").is_file())
        self.assertIn("pnpm@9.15.9", (self.work / "node_modules" / ".modules.yaml").read_text())
        self.assertEqual((self.work / "node_modules" / ".gitignore").read_text(), "*\n")
        self.assert_no_canary()

    def test_yarn_does_not_hand_off_to_a_yarn_path(self):
        self.write("package.json", json.dumps({"name": "y", "version": "1.0.0", "dependencies": {"ms": "2.1.3"}}))
        self.write("yarn.lock", MS_YARN_LOCK)
        self.write(".yarnrc", 'yarn-path "./evil.js"\n--install.ignore-scripts false\n')
        self.write("evil.js", CANARY_JS, executable=True)
        self.write("index.ts", "export {};\n")
        self.commit()
        rows = self.install("index.ts")
        self.assertEqual(rows, [["yarn", "node_modules", "ok", ""]], self.output)
        self.assertTrue((self.work / "node_modules" / "ms" / "package.json").is_file())
        self.assert_no_canary()

    def test_npm_runs_no_script_of_a_file_dependency(self):
        self.write_file_dependency("package-lock.json", json.dumps(LINKED_NPM_LOCK))
        # Packing (install-links) would also run prepare.
        self.write("a/.npmrc", "install-links=true\nscript-shell=/bin/sh\nignore-scripts=false\n")
        self.commit()
        rows = self.install("a/index.ts")
        self.assertEqual(rows, [["npm", "a/node_modules", "ok", ""]], self.output)
        self.assertTrue((self.work / "a" / "node_modules" / "b").is_symlink())
        self.assert_no_canary()

    def write_file_dependency(self, lockfile: str, text: str) -> None:
        # npm ci --ignore-scripts still runs a linked file: package's prepare
        # script; every manager here must not.
        self.write("canary.cjs", CANARY_JS)
        self.write("b/package.json", json.dumps({
            "name": "b", "version": "1.0.0",
            "scripts": {"prepare": "node /work/canary.cjs", "install": "node /work/canary.cjs", "postinstall": "node /work/canary.cjs"},
        }))
        self.write("a/package.json", json.dumps({"name": "a", "version": "1.0.0", "dependencies": {"b": "file:../b"}}))
        self.write(f"a/{lockfile}", text)
        self.write("a/.npmrc", "script-shell=/bin/sh\nignore-scripts=false\n")
        self.write("a/index.ts", "export {};\n")
        self.commit()

    def test_pnpm_runs_no_script_of_a_file_dependency(self):
        self.write_file_dependency("pnpm-lock.yaml", FILE_DEP_PNPM_LOCK)
        rows = self.install("a/index.ts")
        self.assertEqual(rows, [["pnpm", "a/node_modules", "ok", ""]], self.output)
        self.assertTrue((self.work / "a" / "node_modules" / "b").exists())
        self.assert_no_canary()

    def test_yarn_runs_no_script_of_a_file_dependency(self):
        self.write_file_dependency("yarn.lock", FILE_DEP_YARN_LOCK)
        rows = self.install("a/index.ts")
        self.assertEqual(rows, [["yarn", "a/node_modules", "ok", ""]], self.output)
        self.assertTrue((self.work / "a" / "node_modules" / "b").exists())
        self.assert_no_canary()

    def test_a_git_dependency_starts_no_container(self):
        self.write("package.json", json.dumps({"name": "g", "dependencies": {"x": "github:o/x"}}))
        self.write("package-lock.json", json.dumps({"packages": {"node_modules/x": {"resolved": "git+ssh://git@github.com/o/x.git#abc"}}}))
        self.write("index.ts", "export {};\n")
        self.commit()
        rows = self.install("index.ts")
        self.assertEqual(rows, [["npm", "", "skipped", "git-dependency"]])
        self.assertFalse((self.work / "node_modules").exists())

    def test_pip_installs_wheels_and_never_runs_setup_py(self):
        self.write("requirements.txt", "-e .\nsix==1.16.0\n")
        self.write("setup.py", CANARY_PY)
        self.write(".python-version", "3.13\n")
        self.write("app.py", "import six\n")
        self.commit()
        rows = self.install("app.py")
        self.assertEqual(rows, [["pip", ".checks-deps/python/root", "ok", "partial"]], self.output)
        self.assertTrue((self.work / ".checks-deps" / "python" / "root" / "six.py").is_file())
        self.assert_no_canary()

    def test_pip_options_in_the_requirements_file_start_no_container(self):
        self.write("requirements.txt", "--no-binary :all:\nsix==1.16.0\n")
        self.write("app.py", "import six\n")
        self.commit()
        rows = self.install("app.py")
        self.assertEqual(rows, [["pip", "", "skipped", "requirements-options"]])

    def write_cargo_project(self) -> None:
        self.write("Cargo.toml", CARGO_TOML)
        self.write("Cargo.lock", CARGO_LOCK)
        self.write("src/lib.rs", "pub fn f() {}\n")
        self.write("canary.sh", CANARY_SH, executable=True)
        # Read only from the project directory: neither may take effect.
        self.write(".cargo/config.toml", '[build]\nrustc = "/work/canary.sh"\nrustc-wrapper = "/work/canary.sh"\n')
        self.write("rust-toolchain.toml", '[toolchain]\npath = "/work/toolchain"\n')
        self.write("toolchain/bin/cargo", CANARY_SH, executable=True)
        self.write("toolchain/bin/rustc", CANARY_SH, executable=True)
        self.commit()

    def test_cargo_ignores_project_config_and_fills_the_cache(self):
        self.write_cargo_project()
        rows = self.install("src/lib.rs")
        self.assertEqual(rows, [["cargo", ".checks-deps/cargo/registry/src", "ok", ""]], self.output)
        self.assertTrue(list((self.work / ".checks-deps" / "cargo" / "registry" / "src").glob("*/cfg-if-1.0.0")))
        self.assertTrue(list((self.cache / "cargo" / "registry" / "cache").glob("*/cfg-if-1.0.0.crate")))
        self.assert_no_canary()
        # A second job restores from the cache with no network at all.
        shutil.rmtree(self.work / ".checks-deps")
        rows = self.install("src/lib.rs", offline=True)
        self.assertEqual(rows, [["cargo", ".checks-deps/cargo/registry/src", "ok", ""]], self.output)
        self.assertTrue(list((self.work / ".checks-deps" / "cargo" / "registry" / "src").glob("*/cfg-if-1.0.0")))
        self.assert_no_canary()

    def test_go_fills_the_cache_and_a_second_run_needs_no_network(self):
        self.write("go.mod", GO_MOD)
        self.write("go.sum", GO_SUM)
        self.write("main.go", "package main\n\nimport _ \"github.com/google/uuid\"\n\nfunc main() {}\n")
        self.commit()
        rows = self.install("main.go")
        self.assertEqual(rows, [["go", ".checks-deps/go", "ok", ""]], self.output)
        self.assertTrue((self.work / ".checks-deps" / "go" / "github.com" / "google" / "uuid@v1.6.0").is_dir())
        self.assertTrue((self.cache / "go" / "github.com" / "google" / "uuid" / "@v" / "v1.6.0.zip").is_file())
        shutil.rmtree(self.work / ".checks-deps")
        rows = self.install("main.go", offline=True)
        self.assertEqual(rows, [["go", ".checks-deps/go", "ok", ""]], self.output)
        self.assertTrue((self.work / ".checks-deps" / "go" / "github.com" / "google" / "uuid@v1.6.0").is_dir())

    def test_pnpm_workspace_packages_install(self):
        self.write("pnpm-workspace.yaml", "packages:\n  - 'pkgs/*'\n")
        self.write("package.json", json.dumps({"name": "root", "private": True}))
        self.write("pkgs/x/package.json", json.dumps({"name": "x", "version": "1.0.0", "dependencies": {"ms": "2.1.3"}}))
        self.write("pkgs/x/i.ts", "export {};\n")
        self.write("pnpm-lock.yaml", MS_PNPM_LOCK.replace("  .:\n    dependencies:", "  .: {}\n\n  pkgs/x:\n    dependencies:"))
        self.commit()
        rows = self.install("pkgs/x/i.ts")
        self.assertEqual(rows, [["pnpm", "node_modules", "ok", ""]], self.output)
        self.assertTrue((self.work / "pkgs" / "x" / "node_modules" / "ms").exists())
        self.assert_no_canary()

    def test_a_symlinked_node_modules_is_never_mounted(self):
        victim = Path(self.tmp.name) / "victim"
        victim.mkdir()
        (victim / "review.md").write_text("keep")
        self.write("package.json", json.dumps({"name": "s", "version": "1.0.0", "dependencies": {"ms": "2.1.3"}}))
        self.write("yarn.lock", MS_YARN_LOCK)
        (self.work / "node_modules").symlink_to(victim)
        self.write("index.ts", "export {};\n")
        self.commit()
        rows = self.install("index.ts")
        self.assertEqual(rows, [["yarn", "node_modules", "skipped", "unsafe-path"]])
        self.assertEqual(sorted(p.name for p in victim.iterdir()), ["review.md"])


if __name__ == "__main__":
    unittest.main()
